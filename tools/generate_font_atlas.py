"""Regenerate the embedded UI font with Pillow: python tools/generate_font_atlas.py.

Rasterized at 2x logical resolution, medium weight, with padded glyphs so linear
filtering cannot bleed between characters. Only regeneration requires Pillow.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
WIDTH, HEIGHT = 1024, 512
atlas = Image.new('L', (WIDTH, HEIGHT))
draw = ImageDraw.Draw(atlas)
x = y = 2
row_height = 0
faces = []
for size in (11, 14, 18, 24, 32):
    font = ImageFont.truetype(str(ROOT / 'assets/fonts/RobotoCondensed.ttf'), size * 2)
    font.set_variation_by_axes([500])
    ascent, _ = font.getmetrics()
    # Align the visible capital top to drawText's existing top-left origin.
    cap_top = font.getbbox('H')[1]
    glyphs = []
    for code in range(32, 127):
        char = chr(code)
        left, top, right, bottom = font.getbbox(char)
        w, h = right-left, bottom-top
        if x + w + 2 >= WIDTH:
            x = 2; y += row_height + 2; row_height = 0
        assert y + h + 2 < HEIGHT
        draw.text((x-left, y-top), char, font=font, fill=255)
        glyphs.append((x,y,w,h,left/2,(top-cap_top)/2,font.getlength(char)/2))
        x += w + 2; row_height = max(row_height, h)
    faces.append(glyphs)
# RLE allows an embedded font without filesystem lookup or a PNG decoder.
pixels = atlas.tobytes()
runs = []
start = 0
while start < len(pixels):
    end = start + 1
    while end < len(pixels) and pixels[end] == pixels[start] and end-start < 255:
        end += 1
    runs.extend((end-start,pixels[start])); start = end
out = ['// Generated by tools/generate_font_atlas.py; Roboto Condensed, SIL OFL 1.1.',
       '#pragma once', '#include <vector>', '#include <cstddef>', '#include <cstdint>', 'namespace visualizer::ui_font {',
       f'inline constexpr int width = {WIDTH}, height = {HEIGHT};',
       'struct Glyph { int x, y, width, height; float left, top, advance; };',
       'inline constexpr Glyph glyphs[5][95] = {']
for face in faces:
    out.append('{')
    for g in face:
        out.append('{'+','.join(str(v) if i<4 else f'{v:.6f}f' for i,v in enumerate(g))+'},')
    out.append('},')
out.extend(['};','inline constexpr uint8_t runs[] = {'])
for i in range(0,len(runs),32):
    out.append(','.join(map(str,runs[i:i+32]))+',')
out.extend(['};','inline const std::vector<uint8_t>& pixels() {',
            '  static const auto data = [] {', '    std::vector<uint8_t> result(width * height);',
            '    std::size_t offset = 0;', '    for (std::size_t i = 0; i < sizeof(runs); i += 2)',
            '      for (unsigned n = 0; n < runs[i]; ++n) result[offset++] = runs[i + 1];',
            '    return result;', '  }();', '  return data;', '}', '} // namespace visualizer::ui_font'])
(ROOT / 'src/visualization/UiFontAtlas.hpp').write_text('\n'.join(out)+'\n')
print(f'{len(runs)} RLE bytes; glyphs end at y={y+row_height}')
